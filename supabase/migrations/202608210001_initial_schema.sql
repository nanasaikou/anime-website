create or replace function public.sync_completed_episode_progress()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  total_episodes integer;
begin
  if new.status = 'plan' then
    new.episodes_watched := 0;
  elsif new.status = 'completed' and coalesce(new.snapshot->>'episodes', '') ~ '^[0-9]+$' then
    total_episodes := (new.snapshot->>'episodes')::integer;
    if total_episodes > 0 then
      new.episodes_watched := total_episodes;
    end if;
  end if;
  return new;
end;
$$;

create trigger anime_list_entries_sync_progress
before insert or update of status, episodes_watched, snapshot on public.anime_list_entries
for each row execute function public.sync_completed_episode_progress();

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  base_name text;
  candidate text;
  attempt integer := 0;
begin
  base_name := lower(regexp_replace(
    coalesce(
      nullif(new.raw_user_meta_data->>'user_name', ''),
      nullif(new.raw_user_meta_data->>'preferred_username', ''),
      nullif(new.raw_user_meta_data->>'global_name', ''),
      nullif(new.raw_user_meta_data->>'full_name', ''),
      nullif(split_part(new.email, '@', 1), ''),
      'user'
    ),
    '[^A-Za-z0-9_]+', '_', 'g'
  ));
  base_name := trim(both '_' from base_name);
  if char_length(base_name) < 3 then
    base_name := 'user';
  end if;
  base_name := left(base_name, 16);
  candidate := base_name;

  while exists (select 1 from public.profiles where lower(username) = lower(candidate)) loop
    attempt := attempt + 1;
    candidate := left(base_name, 16) || '_' || left(replace(new.id::text, '-', ''), 6) ||
      case when attempt > 1 then attempt::text else '' end;
    candidate := left(candidate, 24);
  end loop;

  insert into public.profiles (id, username, display_name, avatar_url)
  values (
    new.id,
    candidate,
    left(coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', candidate), 80),
    coalesce(new.raw_user_meta_data->>'avatar_url', new.raw_user_meta_data->>'picture')
  );
  return new;
end;
$$;

create trigger auth_user_created_create_profile
after insert on auth.users
for each row execute function public.create_profile_for_new_user();

create or replace function public.are_friends(first_user uuid, second_user uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.friendships friendship
    where friendship.user_a = least(first_user, second_user)
      and friendship.user_b = greatest(first_user, second_user)
  );
$$;

create or replace function public.is_group_member(target_group uuid, target_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.group_members membership
    where membership.group_id = target_group and membership.user_id = target_user
  );
$$;

create or replace function public.send_friend_request(target_username text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_id uuid;
  new_request_id uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;

  select profile.id into target_id
  from public.profiles profile
  where lower(profile.username) = lower(btrim(target_username));

  if target_id is null then raise exception 'Username not found'; end if;
  if target_id = auth.uid() then raise exception 'You cannot add yourself'; end if;
  if public.are_friends(auth.uid(), target_id) then raise exception 'You are already friends'; end if;
  if exists (
    select 1 from public.friend_requests request
    where (request.requester_id = auth.uid() and request.recipient_id = target_id)
       or (request.requester_id = target_id and request.recipient_id = auth.uid())
  ) then raise exception 'A request already exists'; end if;

  insert into public.friend_requests (requester_id, recipient_id)
  values (auth.uid(), target_id)
  returning id into new_request_id;

  delete from public.rejected_friend_requests
  where owner_id = auth.uid() and rejected_user_id = target_id;
  return new_request_id;
end;
$$;

create or replace function public.respond_to_friend_request(request_id uuid, accept_request boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  request_record public.friend_requests%rowtype;
begin
  select * into request_record
  from public.friend_requests
  where id = request_id and recipient_id = auth.uid()
  for update;

  if request_record.id is null then raise exception 'Friend request not found'; end if;

  if accept_request then
    insert into public.friendships (user_a, user_b)
    values (least(request_record.requester_id, request_record.recipient_id), greatest(request_record.requester_id, request_record.recipient_id))
    on conflict do nothing;
    delete from public.rejected_friend_requests
    where (owner_id = request_record.requester_id and rejected_user_id = request_record.recipient_id)
       or (owner_id = request_record.recipient_id and rejected_user_id = request_record.requester_id);
  else
    insert into public.rejected_friend_requests (owner_id, rejected_user_id)
    values (auth.uid(), request_record.requester_id)
    on conflict (owner_id, rejected_user_id)
    do update set rejected_at = now();
  end if;

  delete from public.friend_requests where id = request_record.id;
end;
$$;

create or replace function public.cancel_friend_request(request_id uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  delete from public.friend_requests where id = request_id and requester_id = auth.uid();
$$;

create or replace function public.remove_friend(friend_username text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  friend_id uuid;
begin
  select id into friend_id from public.profiles where lower(username) = lower(btrim(friend_username));
  if friend_id is null then return; end if;
  delete from public.friendships
  where user_a = least(auth.uid(), friend_id) and user_b = greatest(auth.uid(), friend_id);
end;
$$;

create or replace function public.set_group_anime_interest(
  target_group uuid,
  target_anime bigint,
  anime_snapshot jsonb,
  interested boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_group_member(target_group, auth.uid()) then
    raise exception 'You are not a member of this group';
  end if;

  if interested then
    insert into public.group_anime_entries (group_id, anime_id, snapshot, created_by)
    values (target_group, target_anime, coalesce(anime_snapshot, '{}'::jsonb), auth.uid())
    on conflict (group_id, anime_id)
    do update set snapshot = excluded.snapshot;

    insert into public.group_anime_interests (group_id, anime_id, user_id)
    values (target_group, target_anime, auth.uid())
    on conflict do nothing;
  else
    delete from public.group_anime_interests
    where group_id = target_group and anime_id = target_anime and user_id = auth.uid();

    delete from public.group_anime_entries entry
    where entry.group_id = target_group
      and entry.anime_id = target_anime
      and not exists (
        select 1 from public.group_anime_interests interest
        where interest.group_id = entry.group_id and interest.anime_id = entry.anime_id
      );
  end if;
end;
$$;

