-- SoraList shared-data schema for Supabase.
-- Authentication credentials remain in auth.users; this schema stores app data only.

begin;

create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,24}$'),
  display_name text check (char_length(display_name) <= 80),
  bio text not null default '' check (char_length(bio) <= 500),
  avatar_url text,
  region text not null default 'US' check (region ~ '^[A-Z]{2}$'),
  preferences jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index profiles_username_case_insensitive_idx
  on public.profiles (lower(username));

create table public.anime_list_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  anime_id bigint not null,
  status text not null default 'plan' check (status in ('plan', 'watching', 'completed', 'paused', 'dropped')),
  episodes_watched integer not null default 0 check (episodes_watched >= 0),
  rating numeric(3,1) check (rating is null or (rating >= 1 and rating <= 5)),
  snapshot jsonb not null default '{}'::jsonb,
  added_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, anime_id)
);

create index anime_list_entries_anime_id_idx on public.anime_list_entries (anime_id);

create table public.friend_requests (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (requester_id <> recipient_id),
  unique (requester_id, recipient_id)
);

create index friend_requests_recipient_idx on public.friend_requests (recipient_id, created_at desc);

create table public.friendships (
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_a, user_b),
  check (user_a::text < user_b::text)
);

create index friendships_user_b_idx on public.friendships (user_b);

-- A rejection is private to the person who rejected the request. The sender cannot read it.
create table public.rejected_friend_requests (
  owner_id uuid not null references public.profiles(id) on delete cascade,
  rejected_user_id uuid not null references public.profiles(id) on delete cascade,
  rejected_at timestamptz not null default now(),
  primary key (owner_id, rejected_user_id),
  check (owner_id <> rejected_user_id)
);

create table public.groups (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.group_members (
  group_id uuid not null references public.groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'member')),
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);

create index group_members_user_idx on public.group_members (user_id);

create table public.group_anime_entries (
  group_id uuid not null references public.groups(id) on delete cascade,
  anime_id bigint not null,
  snapshot jsonb not null default '{}'::jsonb,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (group_id, anime_id)
);

create table public.group_anime_interests (
  group_id uuid not null,
  anime_id bigint not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (group_id, anime_id, user_id),
  foreign key (group_id, anime_id)
    references public.group_anime_entries(group_id, anime_id) on delete cascade
);

create index group_anime_interests_user_idx on public.group_anime_interests (user_id);

create table public.group_messages (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.groups(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 500),
  system boolean not null default false,
  created_at timestamptz not null default now()
);

create index group_messages_group_created_idx on public.group_messages (group_id, created_at desc);

